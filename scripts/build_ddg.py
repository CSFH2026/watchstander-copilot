"""Turns the DDG source extracts (corpus/ddg/src/*.yaml) into corpus/ddg/*.md.

Each extract entry holds the public source text a procedure is built from, its tier, and its steps.
The tier decides the status line, so a reader always sees how much of a procedure is doctrine:
  taken    - the steps are the source's own action list in the source's order; only equipment names
             are changed to DDG-51 names.
  adapted  - the source actions plus steps the source does not give; `synthetic:` names those steps.
  pattern  - the source gives symptoms, causes, or alarms only; every step is synthetic.
The .md files are generated: edit the extract and rerun this script instead of editing them.

Run:   .venv/bin/python scripts/build_ddg.py
Check: .venv/bin/python scripts/build_ddg.py --check   (fails if the .md files are stale)
"""
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "corpus" / "ddg"
SRC = OUT / "src"
sys.path.insert(0, str(REPO / "api"))

from retrieval.parse import load_corpus  # noqa: E402

TIERS = ("taken", "adapted", "pattern")
ID_RE = re.compile(r"^EOCC-[A-Z]+-[A-Z0-9]+$")
# The corpus line format reserves these words, and front matter reserves the --- fence.
RESERVED = re.compile(r"\brequires:|\bdanger:|---", re.IGNORECASE)
HEADER = "training copy, unclassified."
FOOTER = "Generated by scripts/build_ddg.py from corpus/ddg/src/{file}; do not edit."


class ExtractError(ValueError):
    pass


def cite(registry: dict, src: dict, where: str) -> str:
    ref = src.get("ref")
    if ref not in registry:
        raise ExtractError(f"{where}: unknown source ref {ref!r}; add it to sources.yaml")
    if not str(src.get("text", "")).strip():
        raise ExtractError(f"{where}: source {ref} {src.get('at', '')} has no transcribed text")
    entry = registry[ref]
    at = str(src.get("at", "")).strip()
    parts = [entry["cite"]]
    if at:
        parts.append(f"{entry['locator']} {at}" + (f' "{src["title"]}"' if src.get("title") else ""))
    url = entry["url"].format(n=at) if "{n}" in entry["url"] else entry["url"]
    return ", ".join(parts) + f", {url}"


def status(proc: dict, file: str, refs: list[str], where: str) -> str:
    tier = proc["tier"]
    named = ", ".join(refs)
    if tier == "taken":
        body = f"Steps follow the action list of {named} in source order; equipment names are changed to DDG-51 names."
    elif tier == "adapted":
        synthetic = str(proc.get("synthetic", "")).strip()
        if not synthetic:
            raise ExtractError(f"{where}: an adapted procedure must name its synthetic steps in synthetic:")
        body = f"Steps are adapted from {named} to the DDG-51 plant. Synthetic, not from any source: {synthetic.rstrip('.')}."
    else:
        body = (f"All steps are synthetic. {named} give the symptoms, causes, and alarms only; the steps follow the "
                "casualty control phases of NAVEDTRA Engineman 1 & C chapter 9, not a ship's EOCC card.")
    note = str(proc.get("note", "")).strip()
    return " ".join(x for x in [HEADER, body, note, FOOTER.format(file=file)] if x)


def steps_of(proc: dict, where: str) -> list[str]:
    pid, lines = proc["id"], []
    raw = proc.get("steps") or []
    if len(raw) < 3:
        raise ExtractError(f"{where}: needs at least 3 steps")
    for i, step in enumerate(raw, start=1):
        step = {"text": step} if isinstance(step, str) else dict(step)
        text = re.sub(r"\s+", " ", str(step.get("text", ""))).strip()
        danger = re.sub(r"\s+", " ", str(step.get("danger") or "")).strip()
        if not text or RESERVED.search(text) or RESERVED.search(danger):
            raise ExtractError(f"{where} step {i}: empty, or uses requires:, danger:, or ---")
        req = step.get("requires", "prev")
        if req == "prev":
            req = [] if i == 1 else [i - 1]
        elif req in (None, "none"):
            req = []
        elif not isinstance(req, list):
            req = [int(x) for x in str(req).split(",")]
        # Requiring a later step would make the procedure impossible to finish in any order.
        if any(not (1 <= int(r) < i) for r in req):
            raise ExtractError(f"{where} step {i}: requires {req}, which is not an earlier step")
        req_text = ", ".join(f"{int(r):02d}" for r in req) or "none"
        text = text if text.endswith((".", "!", "?")) else text + "."
        tail = f" requires: {req_text}" + (f". danger: {danger}" if danger else "")
        lines.append(f"{i}. [step: {pid}-{i:02d}] {text}{tail}")
    return lines


def render(proc: dict, group: str, file: str, registry: dict) -> str:
    where = f"{file}: {proc.get('id')}"
    if not ID_RE.match(str(proc.get("id", ""))):
        raise ExtractError(f"{where}: id must look like EOCC-SYSTEM-CODE")
    if proc.get("tier") not in TIERS:
        raise ExtractError(f"{where}: tier must be one of {', '.join(TIERS)}")
    sources = proc.get("sources") or []
    if not sources:
        raise ExtractError(f"{where}: cites no source")
    for key in ("title", "symptoms", "causes", "effects"):
        if not proc.get(key):
            raise ExtractError(f"{where}: {key} is empty")
    refs = list(dict.fromkeys(registry[s["ref"]]["short"].format(at=s.get("at", "")) for s in sources if s.get("ref") in registry))
    front = {
        "procedure_id": proc["id"],
        "title": proc["title"],
        "system": group,
        "tier": proc["tier"],
        "source": " ; ".join(cite(registry, s, where) for s in sources),
        "status": status(proc, file, refs, where),
        "symptoms": proc["symptoms"],
        "causes": proc["causes"],
        "effects": proc["effects"],
    }
    if proc.get("associated"):
        front["associated"] = proc["associated"]
    body = steps_of(proc, where)
    return "---\n" + yaml.safe_dump(front, allow_unicode=True, sort_keys=False, width=10_000) + "---\n" + "\n".join(body) + "\n"


def build() -> dict[str, str]:
    registry = yaml.safe_load((SRC / "sources.yaml").read_text(encoding="utf-8"))
    files: dict[str, str] = {}
    for path in sorted(SRC.glob("*.yaml")):
        if path.name == "sources.yaml":
            continue
        doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        for proc in doc.get("procedures") or []:
            name = f"{proc.get('id')}.md"
            if name in files:
                raise ExtractError(f"{path.name}: {proc.get('id')} is defined twice")
            files[name] = render(proc, doc.get("group", path.stem), path.name, registry)
    known = set(n[:-3] for n in files)
    for name, text in files.items():
        for other in yaml.safe_load(text.split("---", 2)[1]).get("associated", []):
            if other not in known:
                raise ExtractError(f"{name}: associated {other} is not a procedure")
    return files


def main() -> None:
    files = build()
    current = {p.name: p.read_text(encoding="utf-8") for p in OUT.glob("EOCC-*.md")}
    if "--check" in sys.argv:
        stale = sorted(set(files) ^ set(current) | {n for n in files if current.get(n) != files[n]})
        if stale:
            sys.exit(f"{len(stale)} generated files are stale, first: {stale[:3]}. Rerun scripts/build_ddg.py.")
        print(f"{len(files)} procedures up to date")
        return
    for name in set(current) - set(files):
        (OUT / name).unlink()
    for name, text in files.items():
        (OUT / name).write_text(text, encoding="utf-8")
    procs = load_corpus(OUT)
    tiers = {t: sum(1 for p in files.values() if f"\ntier: {t}\n" in p) for t in TIERS}
    print(f"{len(procs)} procedures, {sum(len(p['steps']) for p in procs)} steps -> {OUT}  {tiers}")


if __name__ == "__main__":
    main()
