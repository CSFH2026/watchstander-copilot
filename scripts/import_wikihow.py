"""Turns the wikiHow lists CSV (Hugging Face b-mc2/wikihow_lists) into corpus/wikihow/*.md.

Only result_type == stepped_summary rows are steps; the needed_items and ingredients rows are not.
Each list becomes one procedure file in the same format lane 2 writes by hand, with every step
requiring the one before it. The files are generated: rerun this script instead of editing them.

Run: api/.venv/bin/python scripts/import_wikihow.py ~/Sites/watchstander-copilot-data/raw/hf-wikihow-lists/wikihow_lists.csv
"""
import csv
import re
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "corpus" / "wikihow"
NUMBERED = re.compile(r"^\s*\d+\.\s*(.*)$")
LICENSE = "CC BY-NC-SA 3.0, wikiHow contributors"


def clean(text: str) -> str:
    # The corpus line format reserves these words, and front matter reserves the --- fence.
    text = re.sub(r"\s+", " ", text).strip()
    text = re.sub(r"\b(requires|danger):", r"\1 -", text, flags=re.IGNORECASE)
    return text.replace("---", "-")


def steps_of(result: str) -> list[str]:
    steps: list[str] = []
    for line in result.split("\n"):
        if not line.strip():
            continue
        m = NUMBERED.match(line)
        if m:
            steps.append(clean(m.group(1)))
        elif steps:
            # 27 lines in the set carry no number; they continue the step above them.
            steps[-1] = clean(steps[-1] + " " + line)
    return [s for s in steps if s]


def write(row: dict) -> bool:
    steps = steps_of(row["result"])
    if not steps:
        return False
    pid = f"WH-{row['pageid']}"
    title = clean(row["title"])
    front = {
        "procedure_id": pid,
        "title": title,
        "source": f'wikiHow, "How to {title}", https://www.wikihow.com/index.php?curid={row["pageid"]} ({LICENSE})',
        "status": "stand-in data, not Navy doctrine. Generated by scripts/import_wikihow.py; do not edit.",
        "symptoms": [title, f"how to {title.lower()}"],
    }
    lines = []
    for i, text in enumerate(steps, start=1):
        req = "none" if i == 1 else f"{i - 1:02d}"
        text = text if text.endswith((".", "!", "?")) else text + "."
        lines.append(f"{i}. [step: {pid}-{i:02d}] {text} requires: {req}")
    body = "---\n" + yaml.safe_dump(front, allow_unicode=True, sort_keys=False, width=10_000) + "---\n" + "\n".join(lines) + "\n"
    (OUT / f"{pid}.md").write_text(body, encoding="utf-8")
    return True


def main() -> None:
    csv.field_size_limit(10**9)
    src = Path(sys.argv[1]).expanduser()
    rows = [r for r in csv.DictReader(src.open(encoding="utf-8")) if r["result_type"] == "stepped_summary"]
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("WH-*.md"):
        old.unlink()
    written = sum(write(r) for r in rows)
    print(f"{written} of {len(rows)} stepped lists -> {OUT}")


if __name__ == "__main__":
    main()
